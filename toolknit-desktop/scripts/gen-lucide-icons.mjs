import * as lucide from 'lucide';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const set = new Set([
  // Dynamically swapped via setAttribute in main.js (may not appear in HTML).
  'check',
  'copy',
  'languages',
  'rotate-ccw',
  'sparkles',
]);

function scan(text) {
  for (const m of text.matchAll(/data-lucide=["']([^"']+)["']/g)) {
    set.add(m[1]);
  }
  for (const m of text.matchAll(/setAttribute\(\s*['"]data-lucide['"]\s*,\s*['"]([^'"]+)['"]\s*\)/g)) {
    set.add(m[1]);
  }
}

scan(readFileSync(join(root, 'index.html'), 'utf8'));

function walk(dir) {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    const st = statSync(path);
    if (st.isDirectory()) walk(path);
    else if (/\.(js|html)$/.test(name)) scan(readFileSync(path, 'utf8'));
  }
}
walk(join(root, 'src'));

function toPascal(kebab) {
  return kebab
    .split('-')
    .map((part) => (part ? part[0].toUpperCase() + part.slice(1) : part))
    .join('');
}

const missing = [];
const entries = [];
for (const kebab of [...set].sort()) {
  const pascal = toPascal(kebab);
  if (!(pascal in lucide)) missing.push(`${kebab} -> ${pascal}`);
  else entries.push([kebab, pascal]);
}

if (missing.length) {
  console.error('Missing lucide exports:', missing);
  process.exit(1);
}

const imports = entries.map(([, pascal]) => pascal).join(',\n  ');
// createIcons looks up PascalCase keys (data-lucide="home" → Home).
const mapLines = entries.map(([, pascal]) => `  ${pascal},`).join('\n');

const out = `/* Auto-generated by scripts/gen-lucide-icons.mjs — only icons used in the app. */
import {
  ${imports}
} from 'lucide';

/** Subset of Lucide icons referenced via data-lucide in this app. */
export const appIcons = {
${mapLines}
};
`;

writeFileSync(join(root, 'src', 'lucide-icons.js'), out);
console.log(`Wrote src/lucide-icons.js with ${entries.length} icons`);
